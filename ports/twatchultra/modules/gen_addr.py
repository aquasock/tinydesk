#!/usr/bin/env python3
"""Generate modaddr.h -- the addresses a module must know about.

WHY THIS FILE EXISTS RATHER THAN -D FLAGS. These addresses are compile-time
constants, and a -D flag does not make an object file depend on its VALUE: when
the app was rebuilt the table moved from 0x3c27b8fc to 0x3c27ba74, the -D
changed, and make happily reused the stale .o because its prerequisites were
unchanged. The blob linked against an address the firmware no longer used, the
module's host() read garbage, every call returned MODCALL_ERROR, and the only
symptom was a verdict of -1.

A generated header that every module object DEPENDS ON fixes it structurally:
the header's content changes when an address changes, so make rebuilds.

  gen_addr.py <app.elf> <output.h>
"""
import re
import subprocess
import sys

elf, out = sys.argv[1], sys.argv[2]

WANTED = {
    "MODHOST_PTR_AT": "g_modhost_ptr",     # the API table pointer
    "MODBSS_AT":      "g_modbss",          # the writable bss lent to modules
}

# nm output: "<addr> <type> <name>"
text = subprocess.run(["xtensa-esp32s3-elf-nm", elf],
                      capture_output=True, text=True).stdout

found = {}
for line in text.splitlines():
    parts = line.split()
    if len(parts) == 3 and parts[2] in WANTED.values():
        found[parts[2]] = int(parts[0], 16)

missing = [s for s in WANTED.values() if s not in found]
if missing:
    sys.exit("gen_addr: %s not in %s" % (", ".join(missing), elf))

lines = [
    "/* GENERATED by gen_addr.py -- do not edit.",
    " * Every module object depends on this file, so a moved address rebuilds",
    " * them. A -D flag alone does not: that mistake produced a blob linked",
    " * against a stale table address and a silent verdict of -1. */",
    "#ifndef MODULES_MODADDR_H",
    "#define MODULES_MODADDR_H",
    "",
]
for macro, sym in WANTED.items():
    lines.append("#define %-16s 0x%08xUL   /* %s */" % (macro, found[sym], sym))
lines.append("")
lines.append("#endif")

new = "\n".join(lines) + "\n"
try:
    old = open(out).read()
except FileNotFoundError:
    old = ""

if new != old:
    open(out, "w").write(new)
    print("gen_addr: %s updated" % out)
else:
    print("gen_addr: %s unchanged" % out)
